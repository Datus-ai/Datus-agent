// Post a PR coverage comment from trusted default-branch code.
// The downloaded PR artifact is untrusted data and is never executed.

const fs = require('fs');
const path = require('path');

const MARKER = '<!-- datus-pr-coverage-comment -->';
const MAX_BODY = 65000;

function readArtifactFile(directory, name, maxBytes) {
  const file = path.join(directory, name);
  try {
    const stat = fs.lstatSync(file);
    if (!stat.isFile() || stat.size > maxBytes) {
      throw new Error(`Invalid artifact file: ${name}`);
    }
    return fs.readFileSync(file, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return '';
    throw error;
  }
}

function metricNumber(value) {
  if (typeof value !== 'string' || !/^\d+(?:\.\d+)?$/.test(value)) return null;
  const number = Number(value);
  return Number.isFinite(number) && number >= 0 && number <= 100 ? number : null;
}

function metricCount(value) {
  if (typeof value !== 'string' || !/^\d+$/.test(value)) return null;
  const number = Number(value);
  return Number.isSafeInteger(number) && number <= 1000000 ? number : null;
}

function parseReport(raw) {
  if (!raw) return null;
  let report;
  try {
    report = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!report || typeof report !== 'object' || Array.isArray(report)) return null;
  const metrics = report.metrics || {};
  const overall = metricNumber(metrics.overall);
  const diff = metricNumber(metrics.diff);
  const total = metricCount(metrics.test_total);
  const passed = metricCount(metrics.test_passed);
  const failed = metricCount(metrics.test_failed);
  const skipped = metricCount(metrics.test_skipped);
  if (!Number.isSafeInteger(report.pr_number) || report.pr_number < 1 ||
      !/^[0-9a-f]{40}$/.test(report.head_sha || '') ||
      !Number.isSafeInteger(report.head_repo_id) || report.head_repo_id < 1 ||
      typeof report.head_ref !== 'string' || report.head_ref.length > 255 ||
      !report.head_ref || overall === null || diff === null ||
      total === null || passed === null || failed === null || skipped === null ||
      passed + failed + skipped > total ||
      !['success', 'failure'].includes(metrics.test_outcome)) {
    return null;
  }
  return { ...report, metrics: { overall, diff, total, passed, failed, skipped,
    testOutcome: metrics.test_outcome } };
}

function safeDetails(value) {
  return value.replace(/@/g, '@\u200b').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/````/g, '` ` ` `');
}

function buildBody(report, run, directory) {
  const { overall, diff, total, passed, failed, skipped, testOutcome } = report.metrics;
  const summary = `${passed}/${total} passed` +
    (failed ? `, ${failed} failed` : '') + (skipped ? `, ${skipped} skipped` : '');
  const status = (value) => value >= 80 ? '✅' : '❌';
  const diffReport = safeDetails(readArtifactFile(directory, 'diff-cover-report.md', 30000));
  const testReport = safeDetails(readArtifactFile(directory, 'test-report.md', 30000));
  const details = [
    '<details><summary>Coverage Details</summary>',
    '', '````text', diffReport || 'No diff coverage data.', '````', '</details>', '',
  ];
  if (testReport) {
    details.push('<details><summary>Test Failure Details</summary>', '',
      '````text', testReport, '````', '</details>', '');
  }
  const header = [
    MARKER, '## 📊 PR Test Coverage Report', '',
    '| Metric | Value | Threshold | Status |',
    '|--------|-------|-----------|--------|',
    `| **Overall Coverage** | ${overall}% | - | ℹ️ |`,
    `| **Diff Coverage** | ${diff}% | 80% | ${status(diff)} |`,
    `| **PR Tests** | ${summary} | pass | ${testOutcome === 'success' ? '✅' : '❌'} |`,
    '', `Run: [#${run.run_number}](${run.html_url})`, '',
  ].join('\n');
  const footer = '\n---\n*Generated by pytest-cov + diff-cover*';
  let body = header + details.join('\n') + footer;
  if (body.length > MAX_BODY) {
    body = header + details.join('\n').slice(0, MAX_BODY - header.length - footer.length - 80) +
      '\n\n> Report truncated. See the linked run for complete results.\n' + footer;
  }
  return body;
}

async function postCoverageComment({ github, context, core, artifactDir }) {
  const run = context.payload.workflow_run;
  if (!run || run.event !== 'pull_request' ||
      run.repository?.id !== context.payload.repository?.id) return;

  const report = parseReport(readArtifactFile(artifactDir, 'coverage-comment.json', 10000));
  if (!report) {
    core.warning('No valid PR coverage artifact was found; skipping comment');
    return;
  }

  const owner = context.repo.owner;
  const repo = context.repo.repo;
  const { data: pr } = await github.rest.pulls.get({ owner, repo, pull_number: report.pr_number });
  if (pr.state !== 'open' || pr.base.repo.id !== context.payload.repository.id ||
      pr.head.repo?.id !== report.head_repo_id ||
      (run.head_repository && run.head_repository.id !== report.head_repo_id) ||
      pr.head.ref !== report.head_ref ||
      (run.head_branch && run.head_branch !== report.head_ref) ||
      pr.head.sha !== report.head_sha ||
      ![pr.head.sha, pr.merge_commit_sha].includes(run.head_sha)) {
    core.warning('Coverage artifact does not match the current PR and workflow run; skipping comment');
    return;
  }

  const body = buildBody(report, run, artifactDir);
  const comments = await github.paginate(github.rest.issues.listComments, {
    owner, repo, issue_number: report.pr_number, per_page: 100,
  });
  const existing = comments.find((comment) => comment.user?.type === 'Bot' &&
    comment.body?.includes(MARKER));
  if (existing) {
    await github.rest.issues.updateComment({ owner, repo, comment_id: existing.id, body });
  } else {
    await github.rest.issues.createComment({ owner, repo, issue_number: report.pr_number, body });
  }
}

module.exports = postCoverageComment;
module.exports.parseReport = parseReport;
