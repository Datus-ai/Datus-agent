"""CI guard for removed tools and changed access in builtin Subagent policies.

The reviewed baseline records concrete tools, including wildcard expansions.
Newly selected tools and intentional removals/access changes require reviewing
the policy and explicitly regenerating its complete baseline with --update; unlike
capabilities.json, this baseline must not be regenerated by commit/build hooks.
"""

import argparse
import json
from pathlib import Path

from datus.tools.registry.capabilities import TOOL_CAPABILITIES
from datus.tools.registry.subagent_policy import SUBAGENT_POLICIES, _matches, _provider_tools, resolve_tools

BASELINE_PATH = Path(__file__).with_name("subagent_policy_contracts.json")


def current_policy_contracts() -> dict[str, dict[str, str]]:
    """Inspect raw declarations before runtime filtering can hide stale entries."""
    contracts = {}
    for kind, policy in SUBAGENT_POLICIES.items():
        providers = set(_provider_tools(kind))
        selected = set()
        for pattern in policy.tools:
            matched = {tool for tool in providers if _matches(tool, (pattern,))}
            if not matched:
                raise ValueError(f"{kind}: {pattern} has no tool in its node providers")
            selected.update(matched)
        for tool in sorted(selected):
            if tool not in TOOL_CAPABILITIES:
                raise ValueError(f"{kind}: {tool} has no capability contract")
        rejected = selected - set(resolve_tools(kind, selected))
        if rejected:
            raise ValueError(f"{kind}: tool access violates the type policy: {', '.join(sorted(rejected))}")
        contracts[kind] = {tool: TOOL_CAPABILITIES[tool].access for tool in sorted(selected)}
    return contracts


def validate_policy_contracts(baseline: dict[str, dict[str, str]]) -> None:
    """Require complete recording, then reject removals and access drift."""
    current = current_policy_contracts()
    errors = []
    for kind, actual in current.items():
        for tool in sorted(actual.keys() - baseline.get(kind, {}).keys()):
            errors.append(f"{kind}: {tool} is missing from the contract baseline; record it with --update")
    for kind, required in baseline.items():
        actual = current.get(kind, {})
        for tool, expected in required.items():
            if tool not in actual:
                errors.append(f"{kind}: {tool} was removed from its policy/provider/catalog")
            elif actual[tool] != expected:
                errors.append(f"{kind}: {tool} access changed from {expected} to {actual[tool]}")
    if errors:
        raise ValueError("\n".join(errors))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--update", action="store_true")
    args = parser.parse_args()
    if args.update:
        BASELINE_PATH.write_text(json.dumps(current_policy_contracts(), indent=2, sort_keys=True) + "\n")
    else:
        try:
            validate_policy_contracts(json.loads(BASELINE_PATH.read_text()))
        except ValueError as exc:
            parser.exit(1, f"Subagent policy drift:\n{exc}\nReview the policy before updating its contract baseline.\n")


if __name__ == "__main__":
    main()
